#!/usr/bin/env python3
"""Generate checklist/README.md: the index of every chapter with its lane, gate, state and card count.

    scripts/chapter_index.py          write checklist/README.md
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import sanelib as L  # noqa: E402


def main():
    lanes = json.load(open(os.path.join(L.CHECKLIST, "_lanes.json")))
    stats = json.load(open(os.path.join(L.KB, "data", "stats.json")))["classes"]
    rf = os.path.join(L.CHECKLIST, "_reviewed.txt")
    reviewed = {l.strip() for l in open(rf, encoding="utf-8") if l.strip() and not l.startswith("#")} if os.path.exists(rf) else set()
    by_lane = {n: [] for n in lanes["concurrency"]["order"]}
    total_cards = written = 0
    for c in L.classes():
        if not c.get("chapter"):
            continue
        lane = next((n for n, d in lanes["lanes"].items() if c["slug"] in d["chapters"]), None)
        p = os.path.join(L.CHECKLIST, c["slug"] + ".md")
        st = stats.get(c["slug"], {})
        row = {"c": c, "state": "queued", "items": 0, "gate": "", "st": st}
        if os.path.exists(p):
            ch = L.parse_chapter(p)
            err, _ = L.lint_chapter(ch)
            row["items"], row["gate"] = len(ch["items"]), ch["meta"].get("Applies when", "")
            if err:
                row["state"] = "draft"
            else:
                row["state"] = "reviewed" if c["slug"] in reviewed else "written"
                written += 1
                total_cards += len(ch["items"])
        by_lane.setdefault(lane or "other", []).append(row)
    n = sum(len(v) for v in by_lane.values())
    o = ["# Checklist", "",
         f"{n} chapters, one per vulnerability class. {written} are written ({total_cards} test cards); the rest are in the writing queue.",
         "A card is one falsifiable claim about a target. It declares the facts it `Requires`, and the planner",
         "(`scripts/sane plan`) queues it on an asset only when that asset's recorded facts satisfy them.", "",
         "| File | What it is |", "|---|---|",
         "| [`_facts.json`](_facts.json) | the fact vocabulary: every tag a chapter or card may require, how the fingerprinter or a hunter settles it |",
         "| [`_lanes.json`](_lanes.json) | how chapters group into lanes that different agents can run side by side |",
         "| [`../docs/11-item-schema.md`](../docs/11-item-schema.md) | the chapter and card schema; `scripts/sane lint` enforces it |",
         "| [`../kb/reports/`](../kb/reports/README.md) | the disclosed reports each chapter is built from |", "",
         "States: **queued** (not written yet) · **draft** (on disk, does not lint yet) · **written** (lints clean) · **reviewed** (passed the adversarial review).", ""]
    for lane in lanes["concurrency"]["order"]:
        d = lanes["lanes"][lane]
        o += [f"## Lane `{lane}` — {d['title']}", "", f"{d['thinking']}", "", f"Sessions: {d['sessions']}. Agent: `{d['agent']}`.", "",
              "| Chapter | Prefix | State | Cards | Applies when | In the report library |", "|---|---|---|---|---|---|"]
        for r in by_lane.get(lane, []):
            c, st = r["c"], r["st"]
            link = f"[{c['name']}]({c['slug']}.md)" if r["state"] != "queued" else c["name"]
            lib = f"[{st.get('reports', 0):,} reports, {st.get('paid', 0):,} paid, median ${st.get('median_bounty', 0):,.0f}](../kb/reports/{c['slug']}.md)"
            o.append(f"| {link} | `{c['prefix']}` | {r['state']} | {r['items'] or ''} | `{r['gate'] or '—'}` | {lib} |")
        o.append("")
    o += ["Generated by `scripts/chapter_index.py`. Do not edit by hand."]
    with open(os.path.join(L.CHECKLIST, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(o) + "\n")
    print(f"checklist/README.md: {written}/{n} chapters written, {total_cards} cards")


if __name__ == "__main__":
    main()
